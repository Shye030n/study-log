-- =====================================================================
-- 미니 은행 계정계 실습 DB 셋업 스크립트 (Oracle 23ai Free)
-- 접속 계정: study_log / PDB: FREEPDB1
-- 여러 번 실행해도 됨: 맨 앞에서 기존 테이블/시퀀스를 지우고 다시 만든다.
--
-- 테이블 관계
--   BRANCH 1:N CUSTOMER   (CUSTOMER.MGMT_BRANCH_CD  → 관리지점)
--   BRANCH 1:N ACCOUNT    (ACCOUNT.OPEN_BRANCH_CD   → 개설지점)
--   CUSTOMER 1:N ACCOUNT  (ACCOUNT.CUST_NO)
--   PRODUCT 1:N ACCOUNT   (ACCOUNT.PROD_CD)
--   ACCOUNT 1:N TRX_HIST  (TRX_HIST.ACCT_NO)
--   TRX_HIST.CNTR_ACCT_NO : 이체 상대 계좌. 우리 은행 계좌일 수도, 타행 계좌일 수도
--                           있어서 FK를 걸지 않았다.
--
-- ※ 샘플 데이터라 거래내역은 '계좌 개설 시 신규 입금' + '2026년 7~9월 거래' 위주로만
--   넣었다. (그 사이 기간 거래는 생략. 대신 거래후잔액은 앞뒤가 맞게 계산되어 있음)
-- ※ 대출 계좌는 잔액 = 남은 대출금이고, 거래내역은 넣지 않았다.
-- =====================================================================

SET DEFINE OFF

DROP TABLE IF EXISTS TRX_HIST CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS ACCOUNT  CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS CUSTOMER CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS PRODUCT  CASCADE CONSTRAINTS PURGE;
DROP TABLE IF EXISTS BRANCH   CASCADE CONSTRAINTS PURGE;
DROP SEQUENCE IF EXISTS SEQ_TRX_ID;

-- ---------------------------------------------------------------------
-- 지점
-- ---------------------------------------------------------------------
CREATE TABLE BRANCH (
    BRANCH_CD   VARCHAR2(4)   PRIMARY KEY,
    BRANCH_NM   VARCHAR2(60)  NOT NULL,
    REGION      VARCHAR2(30)  NOT NULL,
    OPEN_DT     DATE
);
COMMENT ON TABLE  BRANCH           IS '지점';
COMMENT ON COLUMN BRANCH.BRANCH_CD IS '지점코드';
COMMENT ON COLUMN BRANCH.BRANCH_NM IS '지점명';
COMMENT ON COLUMN BRANCH.REGION    IS '지역';
COMMENT ON COLUMN BRANCH.OPEN_DT   IS '지점개설일';

-- ---------------------------------------------------------------------
-- 고객
-- ---------------------------------------------------------------------
CREATE TABLE CUSTOMER (
    CUST_NO         VARCHAR2(10)  PRIMARY KEY,
    CUST_NM         VARCHAR2(60)  NOT NULL,
    BIRTH_DT        DATE,
    GRADE           VARCHAR2(10)  CHECK (GRADE IN ('VIP','GOLD','SILVER')),
    MGMT_BRANCH_CD  VARCHAR2(4)   NOT NULL REFERENCES BRANCH(BRANCH_CD),
    JOIN_DT         DATE          NOT NULL,
    PHONE           VARCHAR2(13)
);
COMMENT ON TABLE  CUSTOMER                IS '고객';
COMMENT ON COLUMN CUSTOMER.CUST_NO        IS '고객번호';
COMMENT ON COLUMN CUSTOMER.CUST_NM        IS '고객명';
COMMENT ON COLUMN CUSTOMER.BIRTH_DT       IS '생년월일';
COMMENT ON COLUMN CUSTOMER.GRADE          IS '고객등급(NULL=미산정)';
COMMENT ON COLUMN CUSTOMER.MGMT_BRANCH_CD IS '관리지점코드';
COMMENT ON COLUMN CUSTOMER.JOIN_DT        IS '고객등록일';
COMMENT ON COLUMN CUSTOMER.PHONE          IS '휴대폰번호';

-- ---------------------------------------------------------------------
-- 상품
-- ---------------------------------------------------------------------
CREATE TABLE PRODUCT (
    PROD_CD    VARCHAR2(5)   PRIMARY KEY,
    PROD_NM    VARCHAR2(60)  NOT NULL,
    PROD_TYPE  VARCHAR2(10)  NOT NULL CHECK (PROD_TYPE IN ('예금','적금','대출')),
    INT_RATE   NUMBER(5,2)   NOT NULL,
    SALE_YN    CHAR(1)       DEFAULT 'Y' NOT NULL CHECK (SALE_YN IN ('Y','N'))
);
COMMENT ON TABLE  PRODUCT           IS '상품';
COMMENT ON COLUMN PRODUCT.PROD_CD   IS '상품코드';
COMMENT ON COLUMN PRODUCT.PROD_NM   IS '상품명';
COMMENT ON COLUMN PRODUCT.PROD_TYPE IS '상품유형(예금/적금/대출)';
COMMENT ON COLUMN PRODUCT.INT_RATE  IS '금리(연 %)';
COMMENT ON COLUMN PRODUCT.SALE_YN   IS '판매여부';

-- ---------------------------------------------------------------------
-- 계좌
-- ---------------------------------------------------------------------
CREATE TABLE ACCOUNT (
    ACCT_NO         VARCHAR2(20)  PRIMARY KEY,
    CUST_NO         VARCHAR2(10)  NOT NULL REFERENCES CUSTOMER(CUST_NO),
    PROD_CD         VARCHAR2(5)   NOT NULL REFERENCES PRODUCT(PROD_CD),
    OPEN_BRANCH_CD  VARCHAR2(4)   NOT NULL REFERENCES BRANCH(BRANCH_CD),
    OPEN_DT         DATE          NOT NULL,
    BALANCE         NUMBER(15)    DEFAULT 0 NOT NULL,
    ACCT_STAT       VARCHAR2(10)  NOT NULL CHECK (ACCT_STAT IN ('정상','해지','휴면')),
    CLOSE_DT        DATE
);
COMMENT ON TABLE  ACCOUNT                IS '계좌';
COMMENT ON COLUMN ACCOUNT.ACCT_NO        IS '계좌번호';
COMMENT ON COLUMN ACCOUNT.CUST_NO        IS '고객번호';
COMMENT ON COLUMN ACCOUNT.PROD_CD        IS '상품코드';
COMMENT ON COLUMN ACCOUNT.OPEN_BRANCH_CD IS '개설지점코드';
COMMENT ON COLUMN ACCOUNT.OPEN_DT        IS '개설일';
COMMENT ON COLUMN ACCOUNT.BALANCE        IS '잔액(대출은 남은 대출금)';
COMMENT ON COLUMN ACCOUNT.ACCT_STAT      IS '계좌상태';
COMMENT ON COLUMN ACCOUNT.CLOSE_DT       IS '해지일(해지 계좌만)';

-- ---------------------------------------------------------------------
-- 거래내역
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_TRX_ID START WITH 1 INCREMENT BY 1;

CREATE TABLE TRX_HIST (
    TRX_ID        NUMBER        PRIMARY KEY,
    ACCT_NO       VARCHAR2(20)  NOT NULL REFERENCES ACCOUNT(ACCT_NO),
    TRX_DTM       DATE          NOT NULL,
    TRX_TYPE      VARCHAR2(20)  NOT NULL CHECK (TRX_TYPE IN ('입금','출금','이체입금','이체출금')),
    TRX_AMT       NUMBER(15)    NOT NULL CHECK (TRX_AMT > 0),
    BAL_AFTER     NUMBER(15)    NOT NULL,
    CNTR_ACCT_NO  VARCHAR2(20),
    CHANNEL       VARCHAR2(20)  NOT NULL CHECK (CHANNEL IN ('창구','ATM','인터넷','모바일','자동이체')),
    MEMO          VARCHAR2(100)
);
COMMENT ON TABLE  TRX_HIST              IS '거래내역';
COMMENT ON COLUMN TRX_HIST.TRX_ID       IS '거래ID(SEQ_TRX_ID)';
COMMENT ON COLUMN TRX_HIST.ACCT_NO      IS '계좌번호';
COMMENT ON COLUMN TRX_HIST.TRX_DTM      IS '거래일시(시분 포함)';
COMMENT ON COLUMN TRX_HIST.TRX_TYPE     IS '거래유형';
COMMENT ON COLUMN TRX_HIST.TRX_AMT      IS '거래금액';
COMMENT ON COLUMN TRX_HIST.BAL_AFTER    IS '거래후잔액';
COMMENT ON COLUMN TRX_HIST.CNTR_ACCT_NO IS '상대계좌번호(현금 입출금은 NULL)';
COMMENT ON COLUMN TRX_HIST.CHANNEL      IS '거래채널';
COMMENT ON COLUMN TRX_HIST.MEMO         IS '적요';

